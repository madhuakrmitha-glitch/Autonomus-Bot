"""Translate ``application.yaml`` into an OpenClaw configuration (JSON5 text).

``config/application.example.yaml`` is the normative application inventory; this produces the
framework settings that realise it in OpenClaw 2026.10.x:

* Telegram channel restricted to the owner allowlist (``dmPolicy: allowlist``);
* a single custom model provider pointing at the coordinator's metering gateway with
  ``models.mode: "replace"`` and no fallbacks, so framework-owned calls use open routes only;
* the coordinator's stdio MCP server, and a tool allowlist of ``omca__*`` only;
* the OMCA bridge plugin (commands, approval buttons, fail-closed tool gate).

Secrets stay as ``${ENV}`` substitutions; nothing literal is written.
"""

from __future__ import annotations

import json
from pathlib import Path

from ..config import ApplicationConfig


def translate(cfg: ApplicationConfig, *, mcp_command: str = "omca", plugin_path: str | None = None) -> str:
    owners = [str(i) for i in cfg.owner.telegram_user_ids]
    base = cfg.server.public_base_url or f"http://{cfg.server.host}:{cfg.server.port}"
    planning = cfg.models.route(cfg.models.roles.planning) if cfg.models.roles.planning else None
    model_entry = {
        "id": "planning",
        "name": f"OMCA planning via {planning.id}" if planning else "OMCA planning",
        "input": [m for m in (planning.modalities if planning else ["text"]) if m in ("text", "image")],
        "reasoning": False,
        "contextWindow": planning.context_limit if planning else 32768,
        "maxTokens": planning.max_output_tokens if planning else 4096,
        "cost": {"input": 0, "output": 0, "cacheRead": 0, "cacheWrite": 0},
        "compat": {"supportsTools": True},
    }
    plugin_dir = plugin_path or str(Path(__file__).resolve().parents[3] / "integrations" / "openclaw" / "omca-plugin")
    doc = {
        "gateway": {"mode": "local", "port": 18789, "bind": "loopback",
                    "auth": {"mode": "token", "token": "${OPENCLAW_GATEWAY_TOKEN}"}},
        "channels": {"telegram": {
            "enabled": True,
            "botToken": "${TELEGRAM_BOT_TOKEN}",
            "dmPolicy": "allowlist",
            "allowFrom": owners or ["<owner numeric telegram id>"],
            "groupPolicy": "allowlist",
            "groups": {},
            "capabilities": {"inlineButtons": "dm"},
            "execApprovals": {"enabled": False},
        }},
        "commands": {"ownerAllowFrom": [f"telegram:{o}" for o in owners] or ["telegram:<owner numeric telegram id>"]},
        "models": {"mode": "replace", "providers": {"omca": {
            "baseUrl": f"{base}/v1", "apiKey": "${OMCA_MODEL_GATEWAY_TOKEN}", "api": "openai-completions",
            "timeoutSeconds": 300, "models": [model_entry]}}},
        "agents": {"defaults": {"model": {"primary": "omca/planning", "fallbacks": []},
                                "modelPolicy": {"allow": ["omca/*"]}, "utilityModel": ""}},
        "mcp": {"servers": {"omca": {"command": mcp_command, "args": ["mcp"],
                                     "env": {"OMCA_URL": base, "OMCA_OWNER_TOKEN": "${OMCA_OWNER_TOKEN}"}}}},
        "tools": {"allow": ["omca__*"],
                  "deny": ["group:runtime", "group:fs", "group:ui", "group:web", "group:nodes", "group:automation",
                           "group:sessions", "group:memory", "group:media"],
                  "elevated": {"enabled": False}},
        "plugins": {"enabled": True, "load": {"paths": [plugin_dir]},
                    "entries": {"omca": {"enabled": True, "config": {"sidecarUrl": base, "bridgeToken": "${OMCA_BRIDGE_TOKEN}"}}}},
    }
    header = ("// Generated by `omca openclaw config` from application.yaml. Review before use.\n"
              "// Save as ~/.openclaw/openclaw.json (JSON5). Secrets come from environment variables:\n"
              "// OPENCLAW_GATEWAY_TOKEN, TELEGRAM_BOT_TOKEN, OMCA_MODEL_GATEWAY_TOKEN, OMCA_OWNER_TOKEN, OMCA_BRIDGE_TOKEN.\n"
              "// Schedules are owned by the coordinator; OpenClaw cron is not needed.\n")
    return header + json.dumps(doc, indent=2) + "\n"
